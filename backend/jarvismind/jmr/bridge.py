"""JMR review bridge (JMR-03).

JMR proposals live in the three shared derived tables. The generic lifecycle
endpoints know nothing about JMR rules, lineage or source revalidation, so they
must not be allowed to review a JMR row directly. This bridge is the ONLY review
path for JMR rows:

  1. refuse an obviously non-human actor (existing shared policy);
  2. load the stored proposal and its provenance block;
  3. reject non-PENDING / TTL-expired proposals;
  4. re-read every source memory through the read-only projection and compare
     content hash, status and ``updated_at`` with the evidence captured at
     generation time; any change logically VOIDs the proposal;
  5. hand an approve/reject decision to the EXISTING LifecycleService, which
     performs the authoritative write and its own server-side audit;
  6. append a review snapshot and a fixed-subject JMR review audit row.

The bridge never approves anything by itself. It has no automatic decision
path and no default decision; ``decision`` must be supplied explicitly.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any, Dict, Optional

from ..core.lifecycle_policy import require_human_actor
from ..core.security_gate import assert_safe_text, assert_writable
from ..governance.audit_bus import AuditBus
from ..governance.integration import authorized_operation
from ..governance.projection import ReadOnlyProjection
from ..p1_gate import is_active as governance_is_active
from .auto_execute import AUTHENTICATION_LEVEL, AUTHORIZATION_VERIFICATION
from .errors import (
    JMRPrivacyBlockedError,
    JMRError,
    JMRExpiredError,
    JMRNotFoundError,
    JMRProvenanceError,
    JMRReviewRequiredError,
    JMRStaleSourceError,
    JMRStateConflictError,
)
from .provenance import content_sha256, rule_of
from .sensitive import combine as combine_privacy
from .sensitive import evaluate as evaluate_privacy
from .query import JMRQueryService
from .store import DerivedStore

BRIDGE_SUBJECT = "svc:jmr-review-bridge"
BRIDGE_TRIGGER = "JMR"
_PENDING = "PENDING"


def _parse_iso(value: Any) -> Optional[datetime]:
    if not isinstance(value, str) or not value.strip():
        return None
    raw = value.strip()
    if raw.endswith("Z"):
        raw = raw[:-1] + "+00:00"
    try:
        parsed = datetime.fromisoformat(raw)
    except ValueError:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def _meta_of(raw: Any) -> Dict[str, Any]:
    if not raw:
        return {}
    try:
        payload = json.loads(raw)
    except (ValueError, TypeError):
        return {}
    return payload if isinstance(payload, dict) else {}


class JMRReviewBridge:
    def __init__(
        self,
        *,
        manager,
        query: JMRQueryService,
        lifecycle,
        audit_bus: Optional[AuditBus] = None,
        projection=None,
    ) -> None:
        self.manager = manager
        self.query = query
        self.lifecycle = lifecycle
        self.audit_bus = audit_bus or AuditBus(manager)
        self.projection = projection or ReadOnlyProjection(manager).for_module("JMR")
        self.store = DerivedStore(manager)

    # --------------------------------------------------------------- routing
    def _governed_call(self, *, operation: str, object_ref: str, call):
        """Run an existing lifecycle write under the P1 service boundary.

        When governance is active, the connection-level gate would otherwise
        reject the write as unauthorized. ``authorized_operation`` mints the
        same SERVER principal + one-shot grant used by the other service entry
        points; it does not take any client identity. JMR still never approves
        by itself - the call is inside an explicit human review request.
        """
        if not governance_is_active():
            return call()
        with authorized_operation(
            manager=self.manager,
            operation=operation,
            object_ref=object_ref,
            trigger=BRIDGE_TRIGGER,
        ):
            return call()

    def assert_not_jmr(self, row_id: str) -> None:
        """Reject a generic lifecycle call that targets a JMR-derived row."""
        row = self.store.get_derived(row_id)
        if row is None:
            return
        rule = rule_of(row.get("metadata_json"))
        if rule or str(row.get("source") or "") == "JMR":
            raise JMRReviewRequiredError(
                "This row was generated by JMR and must be reviewed through "
                "POST /api/v1/jmr/proposals/{id}/review",
                detail={
                    "code": "jmr_review_required",
                    "proposal_id": row_id,
                    "rule": rule,
                },
            )

    # ---------------------------------------------------------------- review
    def _audit(
        self,
        *,
        proposal_id: str,
        status: str,
        decision: str,
        actor: str,
        rule: str = "",
        failure_reason: str = "",
        extra: Optional[Dict[str, Any]] = None,
        automated: bool = False,
        authentication_level: Optional[str] = None,
        authorization_verification: Optional[str] = None,
    ) -> str:
        return self.audit_bus.record(
            principal_id=BRIDGE_SUBJECT if not automated else "jmr-auto-execute",
            principal_type="SERVICE",
            operation="JMR_REVIEW",
            object_ref=proposal_id,
            trigger=BRIDGE_TRIGGER,
            status=status,
            failure_reason=failure_reason,
            extra={
                "proposal_id": proposal_id,
                "rule": rule,
                "decision": decision,
                "client_actor_claim": actor,
                "authentication_level": authentication_level or "API_TOKEN_SHARED",
                "authorization_verification_result": (
                    authorization_verification or "NOT_VERIFIED"
                ),
                "automated": automated,
                **(extra or {}),
            },
        )

    def _revalidate(self, proposal_id: str, row: Dict[str, Any]) -> Dict[str, Any]:
        meta = _meta_of(row.get("metadata_json"))
        evidence = meta.get("evidence")
        source_ids = meta.get("source_memory_ids")
        if not isinstance(evidence, list) or not evidence:
            self.store.mark_void(proposal_id, reason="missing_source_evidence")
            self._audit(
                proposal_id=proposal_id,
                status="DENIED",
                decision="revalidate",
                actor="server",
                rule=str(meta.get("rule") or ""),
                failure_reason="missing_source_evidence",
            )
            raise JMRProvenanceError(
                "proposal has no source evidence; rebuild it before review",
                detail={"code": "missing_source_evidence", "proposal_id": proposal_id},
            )
        if not isinstance(source_ids, list) or not source_ids:
            self.store.mark_void(proposal_id, reason="missing_source_ids")
            raise JMRProvenanceError(
                "proposal has no source_memory_ids",
                detail={"code": "missing_source_ids", "proposal_id": proposal_id},
            )

        evidence_ids = [str(item.get("memory_id") or "") for item in evidence]
        if sorted(evidence_ids) != sorted(str(item) for item in source_ids):
            self.store.mark_void(proposal_id, reason="source_evidence_mismatch")
            self._audit(
                proposal_id=proposal_id,
                status="DENIED",
                decision="revalidate",
                actor="server",
                rule=str(meta.get("rule") or ""),
                failure_reason="source_evidence_mismatch",
            )
            raise JMRProvenanceError(
                "source ids and evidence ids do not match",
                detail={
                    "code": "source_evidence_mismatch",
                    "proposal_id": proposal_id,
                },
            )

        digest = content_sha256(
            json.dumps(evidence, ensure_ascii=False, sort_keys=True, default=str)
        )
        for item in evidence:
            memory_id = str(item.get("memory_id") or "")
            current = self.projection.read_memory(memory_id)
            if current is None:
                self.store.mark_void(proposal_id, reason="source_missing")
                self._audit(
                    proposal_id=proposal_id,
                    status="DENIED",
                    decision="revalidate",
                    actor="server",
                    rule=str(meta.get("rule") or ""),
                    failure_reason="source_missing",
                )
                raise JMRStaleSourceError(
                    f"source memory {memory_id} no longer exists",
                    detail={"code": "source_missing", "memory_id": memory_id},
                )
            changed = (
                str(current.get("status") or "") != str(item.get("status") or "")
                or str(current.get("updated_at") or "")
                != str(item.get("updated_at") or "")
                or content_sha256(str(current.get("content") or ""))
                != str(item.get("content_sha256") or "")
            )
            if changed:
                self.store.mark_void(proposal_id, reason="source_changed")
                self._audit(
                    proposal_id=proposal_id,
                    status="DENIED",
                    decision="revalidate",
                    actor="server",
                    rule=str(meta.get("rule") or ""),
                    failure_reason="source_changed",
                    extra={"changed_memory_id": memory_id},
                )
                raise JMRStaleSourceError(
                    f"source memory {memory_id} changed after proposal generation",
                    detail={"code": "source_changed", "memory_id": memory_id},
                )
        return {"source_revalidation_digest": digest, "source_count": len(evidence)}

    def review(
        self,
        proposal_id: str,
        *,
        decision: str,
        actor: str,
        reason: Optional[str] = None,
        chosen_memory_id: Optional[str] = None,
        corrected_content: Optional[str] = None,
        automated: bool = False,
        actor_authentication_level: Optional[str] = None,
        authorization_verification: Optional[str] = None,
    ) -> Dict[str, Any]:
        # R3: 自动执行仍然走同一条审核桥（provenance 重校验、TTL、状态、
        # lifecycle 写入、审计一个都不能少）。区别只有两点：
        #   1. 允许一个明确的自动化身份，而不是伪装成人工；
        #   2. 审计里把身份等级标成 OWNER_AUTHORIZED_AUTOMATION。
        if not automated:
            require_human_actor(actor, operation="JMR proposal review")
        action = (decision or "").strip().lower()
        if action not in {"approve", "reject"}:
            raise JMRStateConflictError(
                "decision must be 'approve' or 'reject'",
                detail={"code": "invalid_review_decision"},
            )

        # JMR-08 audit C-1: review fields are persisted into derived tables
        # (memory_corrections.reason / memory_summaries) and audit detail. They
        # are caller-controlled and must be scanned before any write.
        for field_name, value in (
            ("review_actor", actor),
            ("review_reason", reason),
            ("review_corrected_content", corrected_content),
        ):
            if value:
                assert_safe_text(value, field=field_name)
        if corrected_content:
            assert_writable(corrected_content, field="corrected_content")
        graded_inputs = combine_privacy(
            *(evaluate_privacy(v) for v in (actor, reason, corrected_content) if v)
        )
        if not graded_inputs.may_auto_proceed:
            self._audit(
                proposal_id=proposal_id,
                status="DENIED",
                decision=decision,
                actor="REDACTED",
                rule="",
                failure_reason=(
                    "privacy_input_"
                    f"{graded_inputs.decision.lower()}:{graded_inputs.reason_code}"
                ),
                extra={"privacy": graded_inputs.to_dict()},
            )
            raise JMRPrivacyBlockedError(
                "review reason/content contains sensitive data",
                detail={
                    "code": "jmr_privacy_blocked",
                    "proposal_id": proposal_id,
                    "decision": graded_inputs.decision,
                    "reason_code": graded_inputs.reason_code,
                },
            )

        row = self.store.get_derived(proposal_id)
        if row is None:
            raise JMRNotFoundError(f"proposal {proposal_id!r} not found")
        meta = _meta_of(row.get("metadata_json"))
        rule = str(meta.get("rule") or "")
        if not rule:
            raise JMRProvenanceError(
                "proposal metadata has no rule",
                detail={"code": "proposal_rule_missing", "proposal_id": proposal_id},
            )
        status = str(row.get("status") or "")
        if status != _PENDING:
            raise JMRStateConflictError(
                f"proposal is {status}; only PENDING proposals can be reviewed",
                detail={
                    "code": "proposal_not_pending",
                    "proposal_id": proposal_id,
                    "status": status,
                },
            )

        expires = _parse_iso(meta.get("expires_at"))
        if expires is not None and expires <= datetime.now(timezone.utc):
            self.store.mark_void(proposal_id, reason="ttl_expired")
            self._audit(
                proposal_id=proposal_id,
                status="DENIED",
                decision=action,
                actor=actor,
                rule=rule,
                failure_reason="ttl_expired",
            )
            raise JMRExpiredError(
                "proposal TTL has elapsed; rebuild it before review",
                detail={"code": "jmr_proposal_expired", "proposal_id": proposal_id},
            )

        try:
            revalidation = self._revalidate(proposal_id, row)
        except JMRError:
            raise

        # JMR-08 audit P1-1: a proposal may predate the privacy gate (or have
        # been produced by a caller that bypassed it). Re-evaluate at review so
        # PII/credentials can never be promoted into authoritative memory, and
        # so auto-execute cannot bypass privacy.
        if action == "approve":
            # Cover every content-bearing column used by the three derived
            # tables (summaries store ``content``; merges/corrections use
            # ``new_content``/``new_summary``).
            payloads = [
                str(row.get("new_content") or ""),
                str(row.get("new_summary") or ""),
                str(row.get("content") or ""),
                str(row.get("summary") or ""),
                str(row.get("title") or ""),
                str(corrected_content or ""),
            ]
            graded = combine_privacy(
                *(evaluate_privacy(text) for text in payloads if text)
            )
            if not graded.may_auto_proceed:
                self._audit(
                    proposal_id=proposal_id,
                    status="DENIED",
                    decision=action,
                    actor=actor,
                    rule=rule,
                    failure_reason=(
                        f"privacy_{graded.decision.lower()}:{graded.reason_code}"
                    ),
                    extra={"privacy": graded.to_dict(), **revalidation},
                )
                raise JMRPrivacyBlockedError(
                    "proposal content requires privacy authorization; "
                    "it cannot be approved",
                    detail={
                        "code": "jmr_privacy_blocked",
                        "proposal_id": proposal_id,
                        "decision": graded.decision,
                        "reason_code": graded.reason_code,
                        "required_grants": list(graded.required_grants),
                    },
                )

        try:
            if rule == "SUMMARY":
                self._governed_call(
                    operation="JMR_SUMMARY_REVIEW",
                    object_ref=proposal_id,
                    call=lambda: self.lifecycle.review_summary(
                        proposal_id,
                        decision=action,
                        reason=reason,
                        actor=actor,
                    ),
                )
            elif rule == "MERGE":
                if action == "reject":
                    self._governed_call(
                        operation="JMR_MERGE_REVIEW",
                        object_ref=proposal_id,
                        call=lambda: self.lifecycle.reject_merge(
                            proposal_id, actor=actor
                        ),
                    )
                else:
                    memory_ids = meta.get("source_memory_ids") or []
                    self._governed_call(
                        operation="JMR_MERGE_REVIEW",
                        object_ref=proposal_id,
                        call=lambda: self.lifecycle.confirm_merge(
                            memory_ids,
                            new_content=row.get("new_content"),
                            new_summary=row.get("new_summary"),
                            reason=reason,
                            merge_id=proposal_id,
                            actor=actor,
                        ),
                    )
            elif rule in {"CONFLICT", "STATUS_CHANGE"}:
                if action == "reject":
                    self._governed_call(
                        operation="JMR_CORRECTION_REVIEW",
                        object_ref=proposal_id,
                        call=lambda: self.lifecycle.reject_correction(
                            proposal_id, reason=reason, actor=actor
                        ),
                    )
                else:
                    self._governed_call(
                        operation="JMR_CORRECTION_REVIEW",
                        object_ref=proposal_id,
                        call=lambda: self.lifecycle.resolve_correction(
                            proposal_id,
                            chosen_memory_id=chosen_memory_id,
                            corrected_content=corrected_content,
                            reason=reason,
                            actor=actor,
                        ),
                    )
            else:  # pragma: no cover - rule_of already constrains this
                raise JMRProvenanceError(f"unsupported JMR rule: {rule}")
        except Exception as exc:
            self._audit(
                proposal_id=proposal_id,
                status="DENIED",
                decision=action,
                actor=actor,
                rule=rule,
                failure_reason=f"{type(exc).__name__}:{getattr(exc, 'code', '')}",
                extra=revalidation,
            )
            raise

        result_status = "APPROVED" if action == "approve" else "REJECTED"
        reviewed_at = datetime.now(timezone.utc).isoformat()
        review = {
            "status": result_status,
            "authoritative": False,
            "source": "jmr_review_bridge",
            "decision": action,
            "reviewed_at": reviewed_at,
            "client_actor_claim": actor,
            # R3: 自动执行必须留下可辨认的标记，绝不能看起来像人工批准。
            "automated": bool(automated),
            "authentication_level": actor_authentication_level
            or ("API_TOKEN_SHARED" if not automated else AUTHENTICATION_LEVEL),
            "authorization_verification_result": authorization_verification
            or ("NOT_VERIFIED" if not automated else AUTHORIZATION_VERIFICATION),
            "source_revalidation_digest": revalidation[
                "source_revalidation_digest"
            ],
        }
        self.store.set_review(proposal_id, review)
        audit_id = self._audit(
            proposal_id=proposal_id,
            status=result_status,
            decision=action,
            actor=actor,
            rule=rule,
            extra=revalidation,
            automated=automated,
            authentication_level=actor_authentication_level,
            authorization_verification=authorization_verification,
        )
        return {
            "proposal_id": proposal_id,
            "rule": rule,
            "status": result_status,
            "decision": action,
            "authoritative": False,
            "audit_id": audit_id,
            "review": review,
        }
